-- =====================================================================
--  cleanup_branch_balances.sql — تنضيف أرصدة الفروع من صفوف مش بتاعتها
--  نظام الفجالة ستور المالي
-- =====================================================================
--
--  المشكلة:
--    قاعدة كل فرع فيها **الست مخازن** مش مخزنه هو بس (~14,827 صنف × 6).
--    ووكيل الفرع كان بيقرا `COM_STO_ITEMS` من غير أي فلتر، فكان بيبعت
--    الست مخازن كلها. ومفتاح `hq_branch_balances` هو `(item_id, sto_id)`
--    **من غير عمود فرع** — فالأربع وكلاء كانوا بيمسحوا على بعض كل ٥ دقايق،
--    والرصيد المخزّن بتاع آخر وكيل صادف إنه كتب.
--
--  الإصلاح في الوكلاء:
--    اتضاف `$MyStoId` و`WHERE STO_ID = $MyStoId` في الأربع ملفات، فكل
--    وكيل بقى يبعت **مخزنه هو بس**. وبكده `(item_id, sto_id)` بقى فريد
--    بين الوكلاء ومفيش تصادم، والرفع نزل ٦ أضعاف.
--
--  🔴 ليه الملف ده لازم يتشغّل كمان:
--    الوكيل بعد الإصلاح مابيبعتش المخازن التانية تاني — بس الصفوف القديمة
--    اللي بعتها **قبل** الإصلاح **مابتتمسحش لوحدها**. الإدخال upsert
--    ومابيمسحش أي حاجة. فمن غير التنضيف ده، مخزن ١ و٤ (بتوع الإدارة،
--    ومالهمش وكيل فرع أصلاً) هيفضلوا في الجدول **بأرقام متجمّدة للأبد**.
--    وده أخطر من إنهم يختفوا، لأنه مابيبانش.
--
--  خريطة المخازن (من `hq_stores`):
--    1 الرئيسية      → الإدارة، مفيش وكيل فرع
--    2 فجالة - زهراء → وكيل `zahraa`
--    3 بونجور        → وكيل `bonjour`
--    4 موبايل        → الإدارة، مفيش وكيل فرع
--    5 وادي دجلة     → وكيل `degla`
--    6 اي بي سي      → وكيل `abc`
--
--  ✅ آمن: `hq_branch_balances` جدول **لقطة** مش دفتر أستاذ — الوكلاء
--     بيبعتوا الأرصدة كل ٥ دقايق فأي صف صح بيرجع لوحده. مفيش أي قيد
--     ولا حركة فلوس هنا. وساعة كتابة الملف ده `balance_source = 'hq'`
--     يعني الموقع مش بيقرا من الجدول ده أصلاً.
--
--  🔒 آمن للتكرار: تشغيله تاني مابيمسحش حاجة زيادة.
-- =====================================================================

-- شوف الأول هيتمسح إيه (شغّل ده قبل المسح):
--   SELECT agent_key, sto_id, COUNT(*) AS rows_count
--   FROM hq_branch_balances
--   GROUP BY agent_key, sto_id
--   ORDER BY agent_key, sto_id;

DELETE FROM `hq_branch_balances`
WHERE NOT (
      (`agent_key` = 'zahraa'  AND `sto_id` = 2)
   OR (`agent_key` = 'bonjour' AND `sto_id` = 3)
   OR (`agent_key` = 'degla'   AND `sto_id` = 5)
   OR (`agent_key` = 'abc'     AND `sto_id` = 6)
);

