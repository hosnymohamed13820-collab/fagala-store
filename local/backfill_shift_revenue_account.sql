-- ---------------------------------------------------------------------
-- الخطوة ١ — تأكيد هوية الحساب  🔴 اقرا الناتج قبل ما تكمّل
-- ---------------------------------------------------------------------
-- لازم يرجّع صف واحد اسمه «إيراد مبيعات» ونوعه revenue.
-- لو رجّع اسم تاني أو مارجعش حاجة — **قف**. الرقم اتغيّر ولازم نعرف الجديد.

SELECT id, name, type, is_active
FROM accounts
WHERE id = 109;


-- ---------------------------------------------------------------------
-- الخطوة ٢ — تشغيل جاف: كام صف هيتأثر؟ (مابيغيّرش حاجة)
-- ---------------------------------------------------------------------
-- سجّل الأرقام دي عندك. هنقارن بيها في الخطوة ٦.

SELECT COUNT(*)          AS rows_to_fix,
       MIN(entry_date)   AS from_date,
       MAX(entry_date)   AS to_date,
       SUM(debit)        AS sum_debit,
       SUM(credit)       AS sum_credit
FROM journal_entries
WHERE ref_type = 'shift'
  AND account_id IS NULL;


-- ---------------------------------------------------------------------
-- الخطوة ٣ — نسخة أمان بالـ id قبل أي تعديل (عشان الرجوع)
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS `bak_shift_account_backfill` (
  `entry_id` INT UNSIGNED NOT NULL PRIMARY KEY,
  `done_at`  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT 'الصفوف اللي اتعدّلت في تلحيق حساب إيراد مبيعات — للرجوع';

INSERT IGNORE INTO `bak_shift_account_backfill` (`entry_id`)
SELECT id
FROM journal_entries
WHERE ref_type = 'shift'
  AND account_id IS NULL;

-- تأكيد إن النسخة اتاخدت: الرقم ده لازم يساوي rows_to_fix من الخطوة ٢
SELECT COUNT(*) AS backed_up FROM `bak_shift_account_backfill`;


-- ---------------------------------------------------------------------
-- الخطوة ٤ — التعديل الفعلي
-- ---------------------------------------------------------------------
-- ⚠️ الشرط `account_id IS NULL` مقصود: أي قيد وردية حد حدّدله حساب
--    بإيده قبل كده **مايتلمسش**. مابنكتبش فوق شغل حد.

UPDATE journal_entries
SET account_id = 109
WHERE ref_type = 'shift'
  AND account_id IS NULL;


-- ---------------------------------------------------------------------
-- الخطوة ٥ — تحديث الإعداد عشان الجديد يمشي على نفس الحساب
-- ---------------------------------------------------------------------
-- (لو الكود الجديد اترفع خلاص، ده بيخلّي القديم والجديد على نفس الحساب)

INSERT INTO settings (setting_key, setting_value)
VALUES ('sales_revenue_account_id', '109')
ON DUPLICATE KEY UPDATE setting_value = VALUES(setting_value);


-- ---------------------------------------------------------------------
-- الخطوة ٦ — التأكيد  🔴 لازم تتحقق من التلاتة
-- ---------------------------------------------------------------------

-- (أ) مفيش قيد وردية فاضل من غير حساب → لازم 0
SELECT COUNT(*) AS still_null
FROM journal_entries
WHERE ref_type = 'shift' AND account_id IS NULL;

-- (ب) العدد اللي اتظبط = rows_to_fix من الخطوة ٢
SELECT COUNT(*) AS now_on_revenue
FROM journal_entries
WHERE ref_type = 'shift' AND account_id = 109;

-- (ج) 🔴 الأهم: الفلوس ما اتحركتش.
--     الرقمين دول لازم يساووا sum_debit و sum_credit من الخطوة ٢ بالظبط.
--     لو فرقوا ولو قرش — ارجع بالخطوة ٧ فوراً وكلّمني.
SELECT SUM(debit) AS sum_debit, SUM(credit) AS sum_credit
FROM journal_entries
WHERE ref_type = 'shift' AND account_id = 109;


