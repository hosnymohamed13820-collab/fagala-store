-- =====================================================================
--  upgrade_expected_hours.sql — إضافة عمود الساعات المنتظرة شهرياً للموظفين
--  نظام الفجالة ستور المالي
-- =====================================================================
--
--  بيضيف عمود `expected_monthly_hours` لجدول `employees`:
--    expected_monthly_hours = الساعات المنتظرة من الموظف في الشهر (مثلاً 240 لـ 8 س/يوم، 300 لـ 10 س/يوم)
--
--  ليه اتعمل:
--    تصحيح معادلة حساب الرواتب؛ لحساب سعر الساعة وأيام العمل بناءً على
--    الساعات المنتظرة الفعلية لكل موظف بدلاً من افتراض رقم ثابت (٦ ساعات)،
--    ولمنع صرف مبالغ زائدة بالخطأ. الموظف الذي لم تُحدد ساعاته يتوقف مرتبه
--    حتى يتم تحديدها.
--
--  🔒 صفر تأثير سلبي على البيانات الحالية:
--     - العمود يقبل NULL كقيمة افتراضية (غير محدد).
--     - آمن للتكرار بفضل IF NOT EXISTS.
--
--  التشغيل: phpMyAdmin → SQL → الصق ونفّذ. آمن للتكرار.
--  الملف ده **مايترفعش على الدومين** — بيتشغّل من phpMyAdmin وخلاص.
-- =====================================================================

ALTER TABLE `employees`
  ADD COLUMN IF NOT EXISTS `expected_monthly_hours` DECIMAL(6,2) NULL DEFAULT NULL
  COMMENT 'الساعات المنتظرة من الموظف في الشهر — الأساس اللي المرتب بيتحسب عليه';