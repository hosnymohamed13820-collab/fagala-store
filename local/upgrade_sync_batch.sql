-- =====================================================================
--  ختم الدفعة (batch) لجداول المرآة — نظام الفجالة ستور
--
--  ليه؟
--    الوكيل كان بيمسح جدول الأرصدة بالكامل وبعدين يبعت الدفعات.
--    يعني فيه لحظات الجدول فاضي أو نصه — أي حد يفتح شاشة أرصدة في
--    اللحظة دي يشوف أصفار. ده مقبول كل نص ساعة، ومصيبة كل دقيقتين.
--
--  الطريقة الجديدة:
--    كل صف بيتكتب فوق القديم وعليه ختم الجولة، وفي الآخر بس بيتمسح
--    اللي فضل بختم قديم. الجدول مايفضاش ولا لحظة.
--
--  ⚠️ الترتيب:
--     1) شغّل الملف ده
--     2) ارفع sync_hq.php و agent_hq.ps1 (الاتنين مع بعض)
--     3) شغّل الوكيل يدوي مرة وشوف اللوج
--     4) وبعدين بس غيّر الجدولة
--
--  آمن للتكرار.
-- =====================================================================

ALTER TABLE `hq_balances`
  ADD COLUMN IF NOT EXISTS `batch` VARCHAR(20) NULL
  COMMENT 'ختم الجولة — الصفوف اللي ختمها قديم بتتمسح في الآخر';

ALTER TABLE `hq_unposted`
  ADD COLUMN IF NOT EXISTS `batch` VARCHAR(20) NULL
  COMMENT 'ختم الجولة — نفس الفكرة';

-- الحذف في نهاية كل جولة بيدوّر على العمود ده، فمحتاج فهرس
ALTER TABLE `hq_balances`
  ADD KEY IF NOT EXISTS `idx_hqbal_batch` (`batch`);

ALTER TABLE `hq_unposted`
  ADD KEY IF NOT EXISTS `idx_hqunp_batch` (`batch`);

