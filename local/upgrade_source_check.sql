-- =====================================================================
-- upgrade_source_check.sql — تشييك لكل مصدر حجز/نواقص على حدة
-- نظام الفجالة ستور المالي
--
-- 📌 الحالة الواقعية وليه الأعمدة دي اتعملت:
-- كتاب مثلاً «المعاصر ماس ٣ع» محجوز منه نسخة في فرع الفجالة ونسخة
-- في فرع اي بي سي. مسؤول المشتريات نزل السوق وجاب نسخة واحدة بس.
-- محتاجين نحدد ونشيّك إن النسخة دي راحت لحجز الفجالة (حسب أقدمية
-- تاريخ الحجز)، وإن حجز اي بي سي لسه مستني وما اتجابلوش حاجة.
--
-- قبل الترقية دي، التشييك كان متاح بس على مستوى الصنف ككل
-- (purchase_group_lines.is_checked)، يعني إما الصنف كله اتجاب أو لأ.
-- الأعمدة دي بتسمح بالتشييك على مستوى كل حجز/مصدر بمفرده،
-- مع تسجيل تاريخ التشييك والمستخدم اللي شيّك.
--
-- التشغيل: phpMyAdmin ← SQL ← الصق ونفّذ.
-- آمن للتكرار. المفتاح الأساسي مابيتغيّرش.
-- الملف ده مايترفعش على الدومين (عايش في local/).
-- =====================================================================

ALTER TABLE `purchase_group_sources`
  ADD COLUMN IF NOT EXISTS `is_checked` TINYINT(1) NOT NULL DEFAULT 0
    COMMENT 'المصدر ده اتجابله نسخة — تشييك لكل حجز على حدة',
  ADD COLUMN IF NOT EXISTS `checked_at` TIMESTAMP NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `checked_by` INT NULL DEFAULT NULL;
