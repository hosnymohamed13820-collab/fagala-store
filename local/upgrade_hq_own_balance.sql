-- =====================================================================
--  upgrade_hq_own_balance.sql — الإدارة تبعت رصيد مخزنها في جدول الفروع
--  نظام الفجالة ستور المالي
-- =====================================================================
--
--  الهدف:
--    بعد ما كل وكيل فرع بقى يبعت **مخزنه هو بس**، جدول
--    `hq_branch_balances` بقى فيه مخازن الفروع الأربعة وبس
--    (2 زهراء · 3 بونجور · 5 دجلة · 6 اي بي سي).
--    ناقص **مخزن ١ (الرئيسية)** بتاع الإدارة — ومالوش وكيل فرع.
--
--    من غيره، لو حوّلنا `balance_source` لـ`branch` مخزون الإدارة
--    **يختفي من الموقع كله**.
--
--  الحل (من غير أي تعديل في الباوورشيل):
--    وكيل الإدارة **أصلاً** بيبعت أرصدة كل المخازن على `sync_hq.php`
--    كل جولة. فـ`sync_hq.php` بقى **يعكس** صفوف مخزن الإدارة في
--    `hq_branch_balances` باسم `agent_key = 'hq'` في نفس الحلقة.
--    صفر طلبات زيادة على الشبكة، وصفر تعديل في الوكيل.
--
--  ليه عمود `batch`:
--    وكيل الإدارة بيبعت **لقطة كاملة** كل جولة بختم `batch`، وفي
--    `balances_commit` بيتمسح اللي ختمه قديم. عشان نعمل نفس الحاجة
--    لصفوف `hq` في جدول الفروع (الصنف اللي اتشال من المخزن خالص)،
--    محتاجين نفس الختم هنا.
--    🔴 وكلاء الفروع **مابيبعتوش** ختم — صفوفهم بتفضل `batch = NULL`،
--    وعشان كده المسح مقصور على `agent_key = 'hq'` وبس. صفوف الفروع
--    عمرها ما تتلمس.
--
--  ⚠️ **المفتاح الأساسي مايتغيّرش** — `(item_id, sto_id)` زي ما هو.
--     ده عمود عادي جديد nullable، آمن تماماً على الصفوف الموجودة.
--
--  مخزن ٤ «موبايل» **مش** هنا عن قصد — ده فرع اتقفل.
--
--  🔒 آمن للتكرار: `IF NOT EXISTS`.
-- =====================================================================

ALTER TABLE `hq_branch_balances`
  ADD COLUMN IF NOT EXISTS `batch` VARCHAR(20) NULL DEFAULT NULL
    COMMENT 'ختم جولة وكيل الإدارة — لصفوف agent_key=hq بس، والفروع NULL';

-- فهرس عشان مسح الصفوف القديمة في balances_commit يبقى سريع
ALTER TABLE `hq_branch_balances`
  ADD KEY IF NOT EXISTS `idx_hqbb_agent_batch` (`agent_key`, `batch`);

-- ---------------------------------------------------------------------
--  المخازن اللي الإدارة بتملكها — الموقع بيقراها من هنا مش من الكود،
--  عشان لما فرع يفتح أو يقفل تغيّر صف بدل ما ترفع PHP.
--  فاضية أو مش موجودة = '1' (السلوك الافتراضي في الكود).
--  أرقام مفصولة بفاصلة لو بقوا أكتر من واحد.
-- ---------------------------------------------------------------------
INSERT INTO `settings` (`setting_key`, `setting_value`)
VALUES ('hq_own_sto_ids', '1')
ON DUPLICATE KEY UPDATE `setting_value` = `setting_value`;
