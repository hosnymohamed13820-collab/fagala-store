-- =====================================================================
--  upgrade_perms_version.sql — رقم إصدار الصلاحيات لتحديث الجلسات فوراً
--  نظام الفجالة ستور المالي
-- =====================================================================
--
--  الغرض:
--    إضافة عمود perms_version لجدول users عشان لما الأونر يعدّل صلاحيات
--    أي مستخدم أو يوقفه، الجلسة الحالية للمستخدم تتحدّث في أول ريكوست
--    جاي فوراً من غير ما يحتاج يعمل تسجيل خروج ودخول تاني.
--
--  التشغيل: phpMyAdmin على هوستنجر → SQL → الصق ونفّذ.
--  آمن للتكرار (IF NOT EXISTS).
-- =====================================================================

ALTER TABLE `users`
  ADD COLUMN IF NOT EXISTS `perms_version` INT NOT NULL DEFAULT 1
  COMMENT 'رقم إصدار الصلاحيات — بيزيد مع أي تعديل عشان الجلسات تتحدّث فوراً';
