--
--  بيضيف عمود `has_sales` لجدول `branches`:
--  لتحديد الفروع التي لها مبيعات وتظهر في تقفيل الورديات (كاشير).
--  الإدارة (id = 6) ليس لها مبيعات ولا تظهر في تقفيل الورديات.
--
--  🔒 أمان البيانات:
--     - DEFAULT 1 لتبقى جميع الفروع الحالية تعمل كما هي.
--     - تعديل الإدارة (id = 6) فقط لتصبح has_sales = 0.
--     - عدم المساس بعمود has_finance حتى لا تختفي الإدارة من الخزينة أو الداشبورد.
--
--  التشغيل: phpMyAdmin → SQL → الصق ونفّذ. آمن للتكرار.
-- =====================================================================

USE `u834909335_fagala`;

ALTER TABLE `u834909335_fagala`.`branches`
  ADD COLUMN IF NOT EXISTS `has_sales` TINYINT(1) NOT NULL DEFAULT 1
  COMMENT '1 = له مبيعات ويظهر في تقفيل الورديات، 0 = لا يظهر' AFTER `has_finance`;

UPDATE `u834909335_fagala`.`branches`
   SET `has_sales` = 0
 WHERE `id` = 6;

-- فحص النتيجة
SELECT `id`, `name`, `has_finance`, `has_sales`, `is_active`
  FROM `u834909335_fagala`.`branches`
 ORDER BY `id`;
