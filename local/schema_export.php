<?php
/**
 * schema_export.php — تصدير بنية قاعدة بيانات الموقع (MySQL)
 * نظام الفجالة ستور المالي
 *
 * =====================================================================
 *  بيصدّر **البنية فقط** (CREATE TABLE) — من غير أي بيانات.
 *  يعني مفيش أي باسوردات ولا فلوس ولا أسماء موظفين في الملف الناتج،
 *  فآمن تبعته لأي حد يساعدك في التطوير.
 *
 *  بيطلّع كمان:
 *    • عدد الصفوف في كل جدول (عشان نعرف الجدول شغّال ولا فاضي)
 *    • قائمة الـVIEWs لو فيه
 *    • ملخص سريع فوق الملف
 *
 *  الاستخدام:
 *    1) ارفع الملف جنب باقي ملفات الموقع
 *    2) افتح: https://hosnimanagement.com/schema_export.php
 *       (لازم تكون داخل بحساب الأونر)
 *    3) هينزّل ملف fagala_schema_YYYY-MM-DD.sql
 *    4) ⚠️ امسح الملف من السيرفر بعد ما تخلص
 *
 *  للعرض في المتصفح بدل التحميل:  schema_export.php?view=1
 * =====================================================================
 */
require_once __DIR__ . '/auth.php';

// الأونر بس — الملف ده بيكشف بنية القاعدة كلها
require_login();
if (!is_owner()) {
    http_response_code(403);
    exit('غير مسموح — الأونر فقط.');
}

$pdo    = db();
$view   = isset($_GET['view']);
$today  = date('Y-m-d');
$out    = [];

$out[] = '-- =====================================================================';
$out[] = '--  فجالة ستور — بنية قاعدة البيانات (MySQL)';
$out[] = '--  القاعدة : ' . DB_NAME;
$out[] = '--  التاريخ : ' . date('Y-m-d H:i:s');
$out[] = '--  البيئة  : ' . APP_ENV;
$out[] = '--  ملاحظة  : البنية فقط — مفيش أي بيانات.';
$out[] = '-- =====================================================================';
$out[] = '';

/* ---------------------------------------------------------------------
 *  ١) جمع أسماء الجداول والـviews
 * ------------------------------------------------------------------- */
$tables = [];
$views  = [];
try {
    foreach ($pdo->query('SHOW FULL TABLES')->fetchAll(PDO::FETCH_NUM) as $r) {
        if (strtoupper((string) $r[1]) === 'VIEW') $views[] = (string) $r[0];
        else                                       $tables[] = (string) $r[0];
    }
} catch (Throwable $ex) {
    exit('فشل قراءة قائمة الجداول: ' . htmlspecialchars($ex->getMessage()));
}
sort($tables);
sort($views);

/* ---------------------------------------------------------------------
 *  ٢) عدد الصفوف في كل جدول (فهرس سريع فوق الملف)
 * ------------------------------------------------------------------- */
$counts = [];
foreach ($tables as $t) {
    try {
        $counts[$t] = (int) $pdo->query('SELECT COUNT(*) FROM `' . $t . '`')->fetchColumn();
    } catch (Throwable $ex) {
        $counts[$t] = -1;   // -1 = تعذّر العدّ
    }
}

$out[] = '-- ---------------------------------------------------------------------';
$out[] = '--  الفهرس: ' . count($tables) . ' جدول' . ($views ? ' + ' . count($views) . ' view' : '');
$out[] = '-- ---------------------------------------------------------------------';
foreach ($tables as $t) {
    $n = $counts[$t];
    $out[] = '--   ' . str_pad($t, 34)
           . ' : ' . ($n < 0 ? 'تعذّر العدّ' : $n . ' صف')
           . ($n === 0 ? '   <<< فاضي' : '');
}
$out[] = '';
$out[] = '';

/* ---------------------------------------------------------------------
 *  ٣) بنية كل جدول
 * ------------------------------------------------------------------- */
foreach ($tables as $t) {
    $out[] = '-- =====================================================================';
    $out[] = '--  ' . $t . '   (' . ($counts[$t] < 0 ? '?' : $counts[$t]) . ' صف)';
    $out[] = '-- =====================================================================';
    try {
        $row = $pdo->query('SHOW CREATE TABLE `' . $t . '`')->fetch(PDO::FETCH_NUM);
        // بنشيل AUTO_INCREMENT=رقم عشان الملف مايتغيرش مع كل تصدير
        $ddl = preg_replace('/\s+AUTO_INCREMENT=\d+/', '', (string) ($row[1] ?? ''));
        $out[] = $ddl . ';';
    } catch (Throwable $ex) {
        $out[] = '-- !! فشل: ' . $ex->getMessage();
    }
    $out[] = '';
}

/* ---------------------------------------------------------------------
 *  ٤) الـViews (لو فيه)
 * ------------------------------------------------------------------- */
foreach ($views as $v) {
    $out[] = '-- =====================================================================';
    $out[] = '--  VIEW: ' . $v;
    $out[] = '-- =====================================================================';
    try {
        $row = $pdo->query('SHOW CREATE VIEW `' . $v . '`')->fetch(PDO::FETCH_NUM);
        $out[] = (string) ($row[1] ?? '') . ';';
    } catch (Throwable $ex) {
        $out[] = '-- !! فشل: ' . $ex->getMessage();
    }
    $out[] = '';
}

$out[] = '-- ===== نهاية الملف =====';

$body = implode("\n", $out);

/* ---------------------------------------------------------------------
 *  ٥) الإخراج
 * ------------------------------------------------------------------- */
if ($view) {
    header('Content-Type: text/plain; charset=utf-8');
    echo $body;
    exit;
}

$fname = 'fagala_schema_' . $today . '.sql';
header('Content-Type: application/sql; charset=utf-8');
header('Content-Disposition: attachment; filename="' . $fname . '"');
header('Content-Length: ' . strlen($body));
echo $body;
