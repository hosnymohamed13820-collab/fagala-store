--  نظام الفجالة ستور المالي
-- =====================================================================
--
--  بيضيف عمود external_id لجدول `employees`:
--    external_id = معرّف الموظف في نظام كروينجو (empId) للربط وقت استيراد الحضور
--
--  وفهرس فريد (UNIQUE) على `external_id`:
--    - بيضمن إن كل معرّف كروينجو مربوط بموظف واحد بس في نظامنا.
--    - يسمح بتعدد قيم NULL (الموظفون غير المربوطين يفضلون NULL عادي
--      بدون أي تعارض في MySQL / MariaDB).
--
--  🔒 صفر تأثير على أي بيانات وموظفين حاليين:
--     - العمود الجديد يقبل NULL كقيمة افتراضية لجميع الموظفين المسجلين حالياً.
--     - لا يغيّر أي مفاتيح أساسية أو أجنبية قائمة.
--
--  التشغيل: phpMyAdmin → SQL → الصق ونفّذ. آمن للتكرار.
--  الملف ده **مايترفعش على الدومين** — بيتشغّل من phpMyAdmin وخلاص.
--  ⚠️ لو الفهرس موجود مسبقاً، MySQL قد يظهر خطأ 1061 إذا لم يُستخدم IF NOT EXISTS.
-- =====================================================================

ALTER TABLE `employees`
  ADD COLUMN IF NOT EXISTS `external_id` VARCHAR(32) NULL
  COMMENT 'رقم الموظف في نظام كروينجو (empId) — للربط وقت استيراد الحضور';

ALTER TABLE `employees`
  ADD UNIQUE KEY IF NOT EXISTS `uq_emp_external_id` (`external_id`);
