--
--  (١) إضافة عمود `monthly_deduction` لجدول `employee_advances`:
--      - القسط الشهري المستقطع من راتب الموظف في مسير الرواتب.
--      - القيمة الافتراضية DEFAULT 0.00 و NOT NULL.
--      - قيمة 0.00 تعني خصم السلفة بالكامل دفعة واحدة (نفس السلوك السابق تماماً).
--      - آمن للتكرار: ADD COLUMN IF NOT EXISTS.
--
--  (٢) إضافة عمود `remaining` لجدول `employee_advances`:
--      - المتبقي من أصل السلفة بعد استقطاع الأقساط الشهرية مع مسير الرواتب.
--      - القيمة الافتراضية NULL.
--      - في الصفوف القديمة يكون NULL ويتم التعامل معه برمجياً كأن المتبقي = amount (أصل السلفة).
--      - آمن للتكرار: ADD COLUMN IF NOT EXISTS.
--
--  🔒 صفر تأثير على أي بيانات وسلف سابقة (توافق كامل Backward Compatibility):
--     - الصفوف القديمة تأخذ monthly_deduction = 0.00 و remaining = NULL،
--       وبالتالي تُخصم بالكامل دفعة واحدة عند صرف أول راتب تماماً كما كان في السابق.
--     - عمود `amount` يظل محتفظاً بقيمته كأصل مبلغ السلفة دون تغيير أو إنقاص في مسير الرواتب.
--
--  التشغيل: phpMyAdmin → SQL → الصق ونفّذ. آمن للتكرار.
--  الملف ده **مايترفعش على الدومين** — بيتشغّل من phpMyAdmin وخلاص.
-- =====================================================================

ALTER TABLE `employee_advances`
  ADD COLUMN IF NOT EXISTS `monthly_deduction` DECIMAL(12,2) NOT NULL DEFAULT 0.00 COMMENT 'القسط اللي بيتخصم من الراتب كل شهر — 0 يعني يتخصم بالكامل مرة واحدة',
  ADD COLUMN IF NOT EXISTS `remaining` DECIMAL(12,2) NULL COMMENT 'المتبقي من أصل السلفة — NULL في الصفوف القديمة ويتعامل معها كأن المتبقي = amount';
