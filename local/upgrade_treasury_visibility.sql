--
--  بيضيف عمود `show_in_receipts` لجدول `treasuries`:
--  للتحكم في إظهار أو إخفاء الخزينة في قوائم الاستلام والصرف (الإيصالات).
--
--  🔒 صفر تأثير على أي بيانات موجودة:
--     - القيمة الافتراضية 1 (DEFAULT 1) عشان كل الخزائن الحالية تفضل
--       ظاهرة زي ما هي تماماً من غير أي تغيير سلوك.
--     - إعداد رؤية فقط — مابيمسش الأرصدة ولا كشف الحساب ولا التحويلات.
--
--  التشغيل: phpMyAdmin → SQL → الصق ونفّذ. آمن للتكرار.
--  الملف ده **مايترفعش على الدومين** — بيتشغّل من phpMyAdmin وخلاص.
-- =====================================================================

ALTER TABLE `treasuries`
  ADD COLUMN IF NOT EXISTS `show_in_receipts` TINYINT(1) NOT NULL DEFAULT 1
  COMMENT '1 = تظهر في قوائم الاستلام والصرف، 0 = مخفية من القوائم';
