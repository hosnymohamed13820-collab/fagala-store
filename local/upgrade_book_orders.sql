    (3, 'الإسلامية', 3);

-- ---------------------------------------------------------------------
--  (4) كتالوج الكتب الخارجية
--      المفتاح الحقيقي هو code (كود الصنف) - فريد.
--      البحث في الشاشة بالاسم لان الموردين بيتعاملوا بالاسم.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS book_catalog (
    id         INT AUTO_INCREMENT PRIMARY KEY,
    code       VARCHAR(64)   NOT NULL,
    name       VARCHAR(255)  NOT NULL,
    publisher  VARCHAR(120)  NULL,
    term       VARCHAR(60)   NULL,
    cost       DECIMAL(12,2) NOT NULL DEFAULT 0,
    needed     DECIMAL(12,2) NOT NULL DEFAULT 0,
    is_active  TINYINT(1)    NOT NULL DEFAULT 1,
    created_at TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_code (code),
    KEY idx_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------
--  (5) بنود الطلبيات - سطر لكل (كتاب + مورد)
--      req_qty      = الكمية المطلوبة منه
--      supplier_qty = الكمية اللي المورد يقدر يوفّرها (الادارة بس)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS book_order_lines (
    book_id      INT           NOT NULL,
    supplier_id  INT           NOT NULL,
    req_qty      DECIMAL(12,2) NOT NULL DEFAULT 0,
    supplier_qty DECIMAL(12,2) NULL,
    updated_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    updated_by   INT           NULL,
    PRIMARY KEY (book_id, supplier_id),
    KEY idx_sup (supplier_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------
--  (6) حجز الكتب
--      تنبيه: الـ deposit هنا رقم للعرض والايصال بس - مش بيدخل الخزينة
--      ولا بيعمل اي قيد. لو المطلوب يدخل finance، ده قرار منفصل لازم
--      يتحدد قبل ما نلمسه (فلوس = مانخمّنش).
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS book_reservations (
    id             INT AUTO_INCREMENT PRIMARY KEY,
    branch_id      INT           NULL,
    customer_name  VARCHAR(150)  NOT NULL,
    customer_phone VARCHAR(40)   NULL,
    reserved_by    VARCHAR(150)  NULL,
    deposit        DECIMAL(12,2) NOT NULL DEFAULT 0,
    status         ENUM('open','delivered','cancelled') NOT NULL DEFAULT 'open',
    notes          VARCHAR(500)  NULL,
    created_by     INT           NULL,
    created_at     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_branch (branch_id, status),
    KEY idx_phone (customer_phone)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS book_reservation_lines (
    id             INT AUTO_INCREMENT PRIMARY KEY,
    reservation_id INT           NOT NULL,
    item_id        INT           NOT NULL DEFAULT 0,
    code           VARCHAR(64)   NOT NULL,
    item_name      VARCHAR(255)  NULL,
    qty            DECIMAL(12,2) NOT NULL DEFAULT 0,
    KEY idx_res (reservation_id),
    KEY idx_item (item_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

