-- =====================================================================
--  upgrade_book_orders.sql - طلبيات الكتب + حجز الكتب
--  نظام الفجالة ستور المالي
--
--  بيضيف تابين جداد جوه موديول النواقص:
--    - طلبيات الكتب  : كتالوج الكتب الخارجية + كمية كل مورد
--    - حجز الكتب     : حجوزات العملاء على الكتب الخارجية
--
--  + جدولين مرآة جداد بيملاهم agent_hq.ps1:
--    - hq_item_cats       : تصنيف كل صنف (القسم الاول ITEM_SPEC1)
--    - hq_purchased_items : الاصناف اللي نزلت في اي فاتورة شراء
--
--  شغّله مرة واحدة. آمن للتكرار (IF NOT EXISTS / INSERT IGNORE).
-- =====================================================================

-- ---------------------------------------------------------------------
--  (1) مرآة التصنيفات - القسم الاول لكل صنف
--      المصدر: ITEMS.IS1_ID  ->  ITEM_SPEC1.IS1_NAME1
--      "كتب خارجية" = IS1_ID 1000032 (اتأكدنا منه من داتا الشركة)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS hq_item_cats (
    item_id    INT          NOT NULL,
    is1_id     INT          NOT NULL DEFAULT 0,
    item_name  VARCHAR(255) NULL,
    updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (item_id),
    KEY idx_cat (is1_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- اسماء الاقسام (ITEM_SPEC1) - عشان الاعدادات تختار القسم بالاسم
CREATE TABLE IF NOT EXISTS hq_cat_names (
    is1_id INT          NOT NULL,
    name   VARCHAR(255) NOT NULL,
    PRIMARY KEY (is1_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------
--  (2) الاصناف اللي نزلت في اي فاتورة شراء (SSTT_ID 2 او 6)
--      الوكيل بيبعت DISTINCT ITEM_ID من كل جداول الشهور - مش الفواتير
--      نفسها. الجدول صغير وبيتحدّث مرة في اليوم.
--
--      لو الجدول فاضي (الوكيل لسه ما اتحدّثش)، الكود بيرجع تلقائي
--      لـ hq_invoice_lines + hq_unposted_lines - بس دول من 26_06 وطالع.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS hq_purchased_items (
    item_id INT         NOT NULL,
    batch   VARCHAR(20) NULL,
    PRIMARY KEY (item_id),
    KEY idx_batch (batch)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------
--  (3) موردو الكتب - قابلين للاضافة والتعديل من غير اي كود
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS book_suppliers (
    id         INT AUTO_INCREMENT PRIMARY KEY,
    name       VARCHAR(120) NOT NULL,
    sort_order INT          NOT NULL DEFAULT 0,
    is_active  TINYINT(1)   NOT NULL DEFAULT 1,
    UNIQUE KEY uq_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ملحوظة: الاسماء دي من ملف المواصفات. في ملف الاكسيل الاعمدة كانت
