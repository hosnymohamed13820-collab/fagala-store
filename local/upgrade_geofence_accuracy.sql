-- =====================================================================
--  upgrade_geofence_accuracy.sql — إضافة دقة قراءة الموقع لجدول الحضور
--  نظام الفجالة ستور المالي
-- =====================================================================
--
--  بيضيف عمودين لجدول `attendance`:
--    check_in_acc  = دقة قراءة الموقع بالمتر وقت تسجيل الحضور
--    check_out_acc = دقة قراءة الموقع بالمتر وقت تسجيل الانصراف
--
--  الصفوف القديمة هتاخد NULL — وفي الواجهة بتتعرض «الدقة مش معروفة»
--  (يعني مفيش أي تأثير على البيانات الموجودة).
--
--  آمن للتكرار: IF NOT EXISTS بيمنع الخطأ لو العمود موجود.
--  التشغيل: phpMyAdmin → SQL → الصق ونفّذ.
--  🔴 الملف ده **مايترفعش على الدومين** — بيتشغّل من phpMyAdmin وخلاص.
-- =====================================================================

ALTER TABLE `attendance`
  ADD COLUMN IF NOT EXISTS `check_in_acc`  DECIMAL(8,2) NULL
    COMMENT 'دقة قراءة الموقع بالمتر وقت الحضور — NULL في الصفوف القديمة',
  ADD COLUMN IF NOT EXISTS `check_out_acc` DECIMAL(8,2) NULL
    COMMENT 'دقة قراءة الموقع بالمتر وقت الانصراف — NULL في الصفوف القديمة';
