-- =====================================================================
--  upgrade_salary_mode.sql — إضافة نوع حساب المرتب (ساعات / ثابت) للموظفين
--  نظام الفجالة ستور المالي
-- =====================================================================
--
--  بيضيف عمود `salary_mode` لجدول `employees`:
--    salary_mode = 'hours' (الافتراضي: على الساعات والبصمة)
--                = 'fixed' (مرتب ثابت كامل من غير حساب ساعات أو حضور)
--
--  ليه اتعمل:
--    استثناء موظفي الإدارة الذين لا يسجلون حضوراً بالبصمة (مرتب ثابت كامل)،
--    بحيث يتم صرف الراتب الأساسي كاملاً دون اشتراط تسجيل ساعات منتظرة،
--    مع استمرار تطبيق كافة الخصومات المالية (سلف، جزاءات، عجز عهدة) كالمعتاد.
--
--  🔒 صفر تأثير سلبي على البيانات الحالية (Backward Compatibility):
--     - القيمة الافتراضية 'hours' لجميع الموظفين الحاليين.
--     - آمن للتكرار بفضل IF NOT EXISTS.
--
--  التشغيل: phpMyAdmin → SQL → الصق ونفّذ. آمن للتكرار.
--  الملف ده **مايترفعش على الدومين** — بيتشغّل من phpMyAdmin وخلاص.
-- =====================================================================

ALTER TABLE `employees`
  ADD COLUMN IF NOT EXISTS `salary_mode` VARCHAR(10) NOT NULL DEFAULT 'hours'
  COMMENT 'hours = على الساعات · fixed = مرتب ثابت كامل من غير حساب ساعات';
