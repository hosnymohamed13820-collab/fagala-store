-- ---------------------------------------------------------------------
-- (١) النوع الجديد 'main'
-- ---------------------------------------------------------------------
--  القايمة دي هي **نفس** القايمة الحالية + 'main' في الآخر.
--  الترتيب متسيب زي ما هو عن قصد — تغيير ترتيب قيم الـ ENUM بيغيّر
--  الأرقام الداخلية وممكن يلغبط أي ORDER BY على العمود.
ALTER TABLE `treasuries`
  MODIFY COLUMN `type`
  ENUM('cash','visa','instapay','wallet','card','branch_custody','main')
  NOT NULL
  COMMENT 'main = الخزينة الرئيسية (مستقلة — مش بتدخل في تقفيل الكاشير ولا إذون العهدة)';


-- ---------------------------------------------------------------------
-- (٢) عمود الملاحظات
-- ---------------------------------------------------------------------
ALTER TABLE `journal_entries`
  ADD COLUMN IF NOT EXISTS `notes` TEXT NULL
  COMMENT 'ملاحظات المحاسب — نص حر طويل، بيبان آخر عمود في كشف الحساب والتقارير';

ALTER TABLE `treasury_movements`
  ADD COLUMN IF NOT EXISTS `notes` TEXT NULL
  COMMENT 'نفس ملاحظة القيد — متخزّنة هنا كمان عشان الإيصال يفضل مطابق';


-- ---------------------------------------------------------------------
-- (٣) أثر التعديل بعد الحفظ
-- ---------------------------------------------------------------------
ALTER TABLE `journal_entries`
  ADD COLUMN IF NOT EXISTS `edited_at` TIMESTAMP NULL DEFAULT NULL
  COMMENT 'آخر تعديل على (القيد/البيان/الملاحظات) بعد الحفظ — NULL = ما اتعدلش';

ALTER TABLE `journal_entries`
  ADD COLUMN IF NOT EXISTS `edited_by` INT(10) UNSIGNED NULL DEFAULT NULL
  COMMENT 'users.id بتاع اللي عدّل';


