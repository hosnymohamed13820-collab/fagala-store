--  upgrade_salary_days_decimal.sql — دعم تخزين كسور الأيام بدقة في الرواتب
--  نظام الفجالة ستور المالي
-- =====================================================================
--
--  الهدف:
--    تعديل أعمدة أيام العمل والاستحقاق في جدول `salaries` من INT إلى DECIMAL(7,3)
--    لتخزين الأرقام الدقيقة الفعلية (زي 13.567) بدون ما تتقرّب لـ 14.
--
--  ملاحظة هامة:
--    الرواتب اللي اتصرفت قبل كده أرقام أيامها المتخزّنة مقرّبة ومش هتتغيّر بأثر رجعي.
--    الملف ده بيمنع التقريب في الرواتب المصروفة من هنا ورايح.
--
--  🔒 صفر تأثير على أي بيانات أخرى:
--     - بيعدّل فقط نوع الأعمدة الثلاثة لاستيعاب الكسور العشرية.
--
--  التشغيل: phpMyAdmin → SQL → الصق ونفّذ.
--  الملف ده **مايترفعش على الدومين** — بيتشغّل من phpMyAdmin وخلاص.
--  🔴 متعملش أي استعلام ALTER TABLE من كود PHP أبداً.
-- =====================================================================

ALTER TABLE `salaries`
  MODIFY COLUMN `work_days`     DECIMAL(7,3) NULL COMMENT 'أيام العمل المحسوبة بدقة كسرية من ساعات الحضور',
  MODIFY COLUMN `due_days_calc` DECIMAL(7,3) NULL COMMENT 'أيام الاستحقاق المحسوبة بدقة كسرية قبل أي تعديل',
  MODIFY COLUMN `due_days`      DECIMAL(7,3) NULL COMMENT 'أيام الاستحقاق المعتمدة للصرف الفعلي بدقة كسرية';
