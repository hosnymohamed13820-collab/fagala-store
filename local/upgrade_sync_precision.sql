-- =====================================================================
--  upgrade_sync_precision.sql - دقة علامة المزامنة (watermark)
--  نظام الفجالة ستور المالي
--
--  خلفية:
--    الوكيل كان بيخزّن آخر تعديل بصيغة 'yyyy-MM-dd HH:mm:ss' من غير
--    أجزاء الثانية. SQL Server بيحتفظ بالملي ثانية، يعني فاتورة
--    اتعدّلت 10:00:00.457 بتفضل تحقق الشرط
--        LAST_MODIFY_DATE > '10:00:00'
--    في كل رن، للأبد. فأحدث فاتورة في كل شهر كانت بترجع وتتبعت كل
--    دقيقتين طول اليوم.
--
--    ده اللي طلّع الوكيل لـ~300 ريكوست في الساعة (~7,200 في اليوم)،
--    وفايرول هوستنجر حظر IP الإدارة كله يوم 2026-08-08.
--
--  الإصلاح هنا:
--    نخلي العمود VARCHAR(30) عشان يستحمل '2026-08-08 10:00:00.457'
--    زي ما هي. VARCHAR مش DATETIME(3) عن قصد:
--      • الوكيل بيتعامل معاها كنص من الأول للآخر (المقارنة -gt نصية)
--      • SQL Server بيفهم النص ده كتاريخ عادي جوه الاستعلام
--      • أي عمود DATETIME عادي كان هيقرّب الملي ثانية تاني ويرجّعنا
--        لنفس البق من غير ما ناخد بالنا
--
--  شغّله مرة واحدة، **قبل** ما ترفع agent_hq.ps1 الجديد.
--  آمن للتكرار.
-- =====================================================================

-- الجدول أصلاً موجود من setup، بس بنعمله CREATE احتياطي لو ناقص
CREATE TABLE IF NOT EXISTS hq_invoice_sync_state (
    suffix      VARCHAR(10) NOT NULL,
    last_modify VARCHAR(30) NULL,
    PRIMARY KEY (suffix)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- لو كان DATETIME من قبل، بنحوّله لنص
ALTER TABLE hq_invoice_sync_state
    MODIFY COLUMN last_modify VARCHAR(30) NULL;

-- =====================================================================
--  تصفير العلامات مرة واحدة.
--
--  ليه: العلامات القديمة متخزّنة من غير ملي ثانية. لو سبناها،
--  أول رن هيقارن '...00.457' بـ '...00' ويلاقي فرق فيبعت الفاتورة
--  مرة أخيرة — مش مشكلة، بس التصفير أنضف وبيضمن إن أول رن يبني
--  علامات كاملة الدقة لكل شهر.
--
--  مفيش خطر: الوكيل هيعيد إرسال الفواتير من أول 26_06، والسيرفر
--  بيعمل INSERT ... ON DUPLICATE KEY UPDATE فمفيش تكرار ولا فقدان.
--  الرن الأول هياخد وقت أطول من العادي (دقيقة أو اتنين) — طبيعي.
-- =====================================================================
DELETE FROM hq_invoice_sync_state;

