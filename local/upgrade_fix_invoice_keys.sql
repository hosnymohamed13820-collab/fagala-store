-- =====================================================================
--  إصلاح تصادم مفاتيح المرآة — نظام الفجالة ستور
--
--  المشكلة:
--    STH_ID فريد **داخل جدول الشهر الواحد** بس، مش على مستوى النظام.
--    فاتورة رقمها 12345 في STO_TRANS_HEADER_26_07 وفاتورة تانية
--    رقمها 12345 في STO_TRANS_HEADER_26_08 = رقمين متطابقين لفاتورتين
--    مختلفين تماماً.
--
--    وجدول المرآة كان مفتاحه sth_id لوحده، فالفاتورة اللي تتزامن
--    بعدين بتمسح اللي قبلها (ON DUPLICATE KEY UPDATE). النتيجة:
--      • فواتير بتختفي من الموقع
--      • بنود فاتورة بتظهر في فاتورة تانية
--
--  الحل: المفتاح يبقى (sth_id, suffix) للهيدر
--        و (sth_id, suffix, line_no) للبنود.
--
--  ⚠️ الترتيب مهم:
--     1) شغّل الملف ده
--     2) ارفع الملفات المعدّلة (agent_hq.ps1, sync_hq.php, receiving_lib.php)
--     3) شغّل الوكيل يدوي مرة عشان يعيد إرسال كل الشهور
--        (الملف بيفضّي جدول الحالة فالوكيل هيبعت من الأول)
-- =====================================================================

-- ---------------------------------------------------------------------
-- (1) الهيدر: المفتاح يبقى مركّب (sth_id + suffix)
-- ---------------------------------------------------------------------
ALTER TABLE `hq_invoices` DROP PRIMARY KEY;
ALTER TABLE `hq_invoices` ADD PRIMARY KEY (`sth_id`, `suffix`);

-- ---------------------------------------------------------------------
-- (2) البنود: عمود suffix جديد + مفتاح مركّب
--     العمود ده مكانش موجود خالص — عشان كده بنود الفواتير كانت
--     بتتلخبط من غير ما حد يلاحظ.
-- ---------------------------------------------------------------------
ALTER TABLE `hq_invoice_lines`
  ADD COLUMN IF NOT EXISTS `suffix` VARCHAR(8) NOT NULL DEFAULT ''
  COMMENT 'جدول الشهر — جزء من المفتاح' AFTER `sth_id`;

ALTER TABLE `hq_invoice_lines` DROP PRIMARY KEY;
ALTER TABLE `hq_invoice_lines` ADD PRIMARY KEY (`sth_id`, `suffix`, `line_no`);
ALTER TABLE `hq_invoice_lines` ADD KEY IF NOT EXISTS `idx_hqline_suffix` (`suffix`);

-- ---------------------------------------------------------------------
-- (3) تفضية البيانات المتضرّرة
--     اللي جوه دلوقتي فيه فواتير ممسوحة وبنود مختلطة — مفيش طريقة
--     نعرف بيها الصح من الغلط، فبنمسح ونعيد المزامنة من الأول.
--     ⚠️ ده بيمسح **نسخة** من بيانات نظام الشركة بس.
--        جداول التوزيع (invoice_distribution*) مالهاش أي علاقة
--        ومابتتلمسش — شغلك محفوظ.
-- ---------------------------------------------------------------------
DELETE FROM `hq_invoice_lines`;
DELETE FROM `hq_invoices`;

-- تفضية علامة المزامنة عشان الوكيل يبعت كل الشهور من الأول
DELETE FROM `hq_invoice_sync_state`;
