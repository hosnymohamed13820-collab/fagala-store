-- =====================================================================
--  upgrade_advance_types.sql — تقسيم سلف الموظفين إلى سلف الشهر وسلف مستديمة
--  نظام الفجالة ستور المالي
-- =====================================================================
--
--  إضافة عمود `adv_type` لجدول `employee_advances`:
--      - 'monthly'  (سلفة الشهر): سلفة مسحوبة خلال الشهر الحالي.
--      - 'standing' (سلفة مستديمة): مديونية مرحّلة من شهور سابقة (أموال قديمة).
--      - القيمة الافتراضية DEFAULT 'monthly' و NOT NULL.
--      - عند اعتماد وصرف الرواتب، الجزء غير المسدد من سلفة الشهر يتحول تلقائياً إلى 'standing'.
--      - آمن للتكرار: ADD COLUMN IF NOT EXISTS.
--
--  🔒 أمان كامل على الصفوف السابقة (Backward Compatibility):
--     - الصفوف القديمة تأخذ القيمة الافتراضية 'monthly' تلقائياً.
--     - لا يتم تعديل أي مبالغ أصلية أو تواريخ سابقة.
--
--  التشغيل: phpMyAdmin → SQL → الصق ونفّذ. آمن للتكرار.
--  الملف ده **مايترفعش على الدومين** — بيتشغّل من phpMyAdmin وخلاص.
-- =====================================================================

ALTER TABLE `employee_advances`
  ADD COLUMN IF NOT EXISTS `adv_type` ENUM('monthly','standing') NOT NULL DEFAULT 'monthly'
  COMMENT 'monthly = سلفة الشهر الحالي · standing = سلفة مستديمة متراكمة من شهور فاتت';
