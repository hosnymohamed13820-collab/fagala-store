--  upgrade_scan_wake.sql - إشارة إيقاظ وكيل السكانر
--  نظام الفجالة ستور المالي
--
--  الخلفية:
--    fagala_scanner_agent.ps1 كان بيسأل scan_pull.php كل 800 جزء من
--    الثانية على طول = ~100,000 نداء في اليوم من كل كمبيوتر عليه
--    الوكيل. وده أكبر مصدر حمل في المشروع كله - أكتر من وكيل
--    المزامنة بـ14 ضعف.
--
--    وكمان مكانش فيه أي تراجع لما الموقع ما يردش، فأثناء حظر
--    2026-08-08 فضل يخبط على IP محظور بنفس المعدل.
--
--  الفكرة:
--    الموبايل بيسيب علامة "أنا فاتح الكاميرا" على الجلسة، والوكيل
--    بيشوفها في رد scan_pull العادي (من غير أي نداء زيادة):
--
--      wake_until > NOW()  ->  الوكيل يسأل كل 400ms  (وقت المسح)
--      غير كده             ->  كل 10 ثواني           (ساكن)
--
--    10 ثواني مقصودة: قايمة الأجهزة في remote_scan.php بتعتبر أي
--    جهاز مامرّش عليه أكتر من 15 ثانية "أوفلاين"، فلازم نفضل تحتها.
--
--  شغّله مرة واحدة. آمن للتكرار.
-- =====================================================================

-- MySQL مابيدعمش ADD COLUMN IF NOT EXISTS في كل النسخ، فبنعملها
-- بالطريقة الآمنة: نشوف العمود موجود ولا لأ الأول.
SET @c := (
    SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME   = 'scan_agents'
      AND COLUMN_NAME  = 'wake_until'
);

SET @s := IF(@c = 0,
    'ALTER TABLE scan_agents ADD COLUMN wake_until DATETIME NULL AFTER last_seen',
    'SELECT "wake_until موجود بالفعل" AS msg'
);

PREPARE stmt FROM @s;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

