-- ---------------------------------------------------------------
-- (١) تنضيف الحسابات — شيل الصفوف المتولّدة تلقائياً
-- ---------------------------------------------------------------
--  جدول accounts فيه نوعين صفوف:
--    * صفوف الشجرة الحقيقية (src_table = NULL) ← دي اللي عايزينها
--    * صفوف متولّدة لكل مورد ولكل موظف (src_table = 'suppliers'
--      أو 'employees') ← دي لازم تتشال
--
--  ليه تتشال: الدالة sync_dynamic_accounts() في finance.php:270 بتولّد
--  الصفوف دي لوحدها من جدول suppliers و employees. لو سبناها اللي
--  جاية من الفجالة، هيبقى عندك تكرار وحسابات بتشاور على موظفين
--  مش موجودين في إشراقة أصلاً.
DELETE FROM `accounts` WHERE `src_table` IS NOT NULL;

-- ---------------------------------------------------------------
-- (٢) تصفير أرصدة الموردين
-- ---------------------------------------------------------------
--  🔴 مهم: عمود balance اللي جه من الفجالة هو رصيد **الفجالة** مع
--  المورد. إشراقة بتشتغل مع نفس الموردين بس حسابها معاهم مستقل تماماً،
--  فبتبدأ من الصفر مع كل واحد فيهم.
UPDATE `suppliers` SET `balance` = 0.00;

-- ---------------------------------------------------------------
-- (٣) دور الكاشير
-- ---------------------------------------------------------------
--  الصلاحيات في النظام ده **لكل مستخدم** مش لكل دور — بتتخزن في
--  user_permissions.module_key. يعني الدور اسم وتصنيف بس، والصلاحيات
--  الفعلية بتتظبط لكل كاشير من شاشة المستخدمين بعد ما تعمله حساب.
--
--  ودور الأونر مش محتاج تعمله — صفحة setup_owner.php بتعمله لوحدها.
INSERT INTO `roles` (`name`, `name_ar`, `is_owner`)
SELECT * FROM (SELECT 'cashier' AS n, 'كاشير' AS na, 0 AS io) AS t
WHERE NOT EXISTS (
    SELECT 1 FROM `roles` WHERE `name` = 'cashier'
);

